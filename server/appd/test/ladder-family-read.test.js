'use strict';
// What model the headroom tick reads a session as being on, right after the
// ladder moved it with the `/model` picker.
//
// The picker's `s` key switches the session and Claude Code writes the switch
// as its command output — `Set model to <label> for this session only` — but no
// assistant record names the new model until the session next replies. The
// tick read the model off the last assistant record, so on the very next pass a
// session the ladder had just moved to opus read as Fable again: it went back
// into `fable-sessions` (its spawns held by STOP-FABLE), and after the weekly
// reset its move back up carried family `opus` while the session "was" fable,
// and the send queue dropped it on every tick.
//
// readSessionModel is lifted out of huginn-appd.js and run against real
// transcripts on disk, with the real lib/transcript reader under it.

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const headroomLib = require('../lib/headroom');
const sentinelsLib = require('../lib/sentinels');
const typing = require('../lib/typing');
const { readTranscript } = require('../lib/transcript');
const paneLib = require('../lib/pane');
const { lift } = require('./ladder-lift');

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), `ladder-family-${process.pid}-`));
let clock = Date.parse('2026-10-19T20:00:00Z');
const at = () => new Date((clock += 1000)).toISOString();

// Record shapes as Claude Code writes them (compact JSON, one per line).
const user = (text) => ({ type: 'user', message: { role: 'user', content: text }, origin: { kind: 'human' }, timestamp: at() });
const reply = (model) => ({ type: 'assistant', message: { model, role: 'assistant', content: [{ type: 'text', text: 'done' }] }, timestamp: at() });
const turnEnd = () => ({ type: 'system', subtype: 'turn_duration', durationMs: 900, timestamp: at() });
const caveat = () => ({ type: 'user', isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>' }, timestamp: at() });
const command = (name, args = '') => ({ type: 'user', message: { role: 'user', content: `<command-name>${name}</command-name>\n            <command-message>${name.slice(1)}</command-message>\n            <command-args>${args}</command-args>` }, timestamp: at() });
const stdout = (text) => ({ type: 'user', message: { role: 'user', content: `<local-command-stdout>${text}</local-command-stdout>` }, timestamp: at() });
/** What the picker leaves behind for `s` on `label` (measured on 2.1.280 and 2.1.296). */
const pickerSwitch = (label) => [caveat(), command('/model'), stdout(`Set model to \`${label}\` for this session only`)];

function transcript(name, records) {
  const file = path.join(tmp, `${name}.jsonl`);
  fs.writeFileSync(file, `${records.map((r) => JSON.stringify(r)).join('\n')}\n`);
  return file;
}

function reader(files) {
  return lift(['readSessionModel'], {
    fs, path, Buffer, readTranscript, headroomLib, paneLib, Date, JSON,
    readSessionState: (name) => (files[name] ? { sessionId: `sid-${name}`, transcript: files[name] } : null),
  }, { helpers: ['lastModelRecord', 'localCommandOutput', 'LADDER_FEEDBACK_RE', 'transcriptTail'] }).readSessionModel;
}

/** The tick's own line: the family read, or the record's when the read has none. */
const familyNow = (read, was) => headroomLib.familyOf(read.model) || was;

test('right after the picker moves a session to opus, it reads as opus', () => {
  const files = {
    moved: transcript('moved', [user('refactor it'), reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Opus 5')]),
  };
  const read = reader(files)('moved');
  assert.equal(familyNow(read, 'opus'), 'opus', `read ${JSON.stringify(read.model)}`);
});

test('the 1M-context row and the older spelling of the line both count', () => {
  const files = {
    big: transcript('big', [reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Opus 5.5 (1M context)')]),
    old: transcript('old', [reply('claude-fable-5-1'), turnEnd(), caveat(), command('/model'),
      stdout('Model set to Sonnet 5 for this session only')]),
    // Builds that keep command output in a system record.
    sys: transcript('sys', [reply('claude-fable-5-1'), turnEnd(),
      { type: 'system', subtype: 'local_command', content: '<local-command-stdout>Set model to `Opus 5` for this session only</local-command-stdout>', timestamp: at() }]),
  };
  const read = reader(files);
  assert.equal(familyNow(read('big'), null), 'opus');
  assert.equal(familyNow(read('old'), null), 'sonnet');
  assert.equal(familyNow(read('sys'), null), 'opus');
});

const apiError = () => ({
  type: 'assistant', isApiErrorMessage: true, apiErrorStatus: 529,
  message: { model: '<synthetic>', content: [{ type: 'text', text: 'API Error: overloaded' }] }, timestamp: at(),
});

test('an API error after the switch names no model and hides nothing', () => {
  const files = {
    // The first turn on the new model was refused: the switch is still the
    // newest thing that says which model this is.
    refused: transcript('refused', [reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Opus 5'),
      user('go on'), apiError()]),
  };
  assert.equal(familyNow(reader(files)('refused'), 'fable'), 'opus');
});

test('whatever came AFTER the switch still wins', () => {
  const files = {
    // The owner typed `/model fable` afterwards: that is the model now.
    typed: transcript('typed', [reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Opus 5'),
      caveat(), command('/model', 'fable'), stdout('Set model to Fable 5.1')]),
    // And a later reply on another model is the model, whatever was picked.
    later: transcript('later', [reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Opus 5'),
      user('go on'), reply('claude-sonnet-5'), turnEnd()]),
    // A switch to a row that names no family says nothing about the family.
    dflt: transcript('dflt', [reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Default (recommended)')]),
  };
  const read = reader(files);
  assert.equal(familyNow(read('typed'), null), 'fable');
  assert.equal(familyNow(read('later'), null), 'sonnet');
  assert.equal(familyNow(read('dflt'), null), 'fable', 'the last reply is all there is to go on');
});

test('the moved session is neither held as a Fable session nor has its move back dropped', () => {
  const files = {
    x: transcript('x', [user('refactor it'), reply('claude-fable-5-1'), turnEnd(), ...pickerSwitch('Opus 5')]),
  };
  // The ladder's confirmed move left this record, family opus; the tick then reads it again.
  const rec = { name: 'x', family: 'opus', ladder: { from: 'fable', to: 'opus', delivery: 'confirmed' } };
  rec.family = familyNow(reader(files)('x'), rec.family);

  // writeSentinels lists every session whose family reads fable.
  const dir = path.join(tmp, 'headroom');
  const { writeSentinels } = lift(['writeSentinels'], {
    sentinelsLib, HEADROOM_DIR: dir, log: () => { },
  });
  const state = { sessions: { 'sid-x': rec }, sentinels: { STOP: null, 'STOP-FABLE': null } };
  writeSentinels({ STOP: false, STOP_FABLE: true, reasons: { 'STOP-FABLE': 'weekly_fable 95%' } }, state, {});
  assert.equal(fs.readFileSync(path.join(dir, 'fable-sessions'), 'utf8'), '',
    'STOP-FABLE must not bind the session the ladder moved off Fable');

  // The move back up is queued as a `kind:'model'` job carrying the family it
  // moves FROM, and the queue drops it when the session reads otherwise.
  const job = { automated: true, kind: 'model', family: rec.ladder.to };
  assert.equal(typing.dropReason(job, { family: rec.family }), null);
});
