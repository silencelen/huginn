'use strict';
// What the automated-send drop rule counts as a PERSON, record by record.
//
// `hasHumanUserRecord` decides "the owner typed first", which drops a queued
// automated message. Records nobody typed used to pass it: Claude Code's own
// (a background task's notification, a command's output) and appd's own (a
// pasted message is recorded exactly like a typed one). The shapes below are
// the real ones, from test/fixtures/transcripts.

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const t = require('../lib/typing');

const FIX = path.join(__dirname, 'fixtures', 'transcripts');
const lines = (f) => fs.readFileSync(path.join(FIX, f), 'utf8').split('\n').filter((l) => l.trim());
const one = (o) => `${JSON.stringify(o)}\n`;

test('a background task\'s notification is Claude Code talking to itself', () => {
  const echo = lines('task-notification-echo.jsonl')[3];
  assert.equal(JSON.parse(echo).origin.kind, 'task-notification', 'the fixture is the record it should be');
  assert.equal(t.hasHumanUserRecord(`${echo}\n`), false);
});

test('a command\'s output is not a person, the command somebody typed is', () => {
  const [command, output] = lines('slash-command.jsonl');
  assert.equal(t.hasHumanUserRecord(`${output}\n`), false, '<local-command-stdout> is what the command printed');
  assert.equal(t.hasHumanUserRecord(`${command}\n`), true, 'a slash command a person typed still counts');
  for (const out of ['<local-command-stderr>no such model</local-command-stderr>',
    '<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>',
    '<local-command-caveat>Caveat: the messages below were generated by the user</local-command-caveat>']) {
    assert.equal(t.hasHumanUserRecord(one({ type: 'user', message: { content: out } })), false, out);
  }
  assert.equal(t.hasHumanUserRecord(one({ type: 'user', message: { content: '<bash-input>git status</bash-input>' } })), true,
    'and neither is the `!` command a person ran');
});

test('a record the caller typed itself is not the owner, matched however it was recorded', () => {
  const sent = '[Huginn] Relayed message from proj/lead:\nre-run the import\n[End of message from proj/lead.]';
  const ours = new Set([t.promptSpelling(sent), t.promptSpelling('/model')]);
  const isOurs = (s) => ours.has(s);
  // Recorded with its line ends changed and trimmed, as Claude Code does.
  const pasted = one({
    type: 'user', message: { role: 'user', content: sent.replace(/\n/g, '\r\n').trimEnd() },
    origin: { kind: 'human' }, promptSource: 'typed',
  });
  assert.equal(t.hasHumanUserRecord(pasted), true, 'without the memory it is indistinguishable from typing');
  assert.equal(t.hasHumanUserRecord(pasted, { ours: isOurs }), false);
  // The ladder's own `/model`, as Claude Code records the command.
  const model = one({ type: 'user', message: { content: '<command-name>/model</command-name>\n            '
    + '<command-message>model</command-message>\n            <command-args></command-args>' } });
  assert.equal(t.hasHumanUserRecord(model, { ours: isOurs }), false);
  // Anything else in the same slice is still a person.
  const person = one({ type: 'user', message: { content: 'wait, not that one' }, origin: { kind: 'human' }, promptSource: 'typed' });
  assert.equal(t.hasHumanUserRecord(`${pasted}${person}`, { ours: isOurs }), true);
  const image = one({ type: 'user', message: { content: [{ type: 'image', source: { type: 'base64', data: 'AA==' } }] } });
  assert.equal(t.hasHumanUserRecord(image, { ours: () => true }), true, 'an image was attached by somebody');
});

test('scanForHuman hands the memory through to the record test', () => {
  const sent = 'Your usage limit has reset. Continue the task.';
  const buf = Buffer.from(one({ type: 'user', message: { content: sent }, origin: { kind: 'human' } }));
  const read = (at, max) => ({ buf: buf.subarray(at, at + max), start: at });
  assert.equal(t.scanForHuman({ at: 0 }, read), true);
  assert.equal(t.scanForHuman({ at: 0 }, read, t.HUMAN_SCAN_MAX_BYTES, { ours: (s) => s === t.promptSpelling(sent) }), false);
});
