'use strict';
// lib/transcript.js finds Claude Code's tags in transcript text with indexOf
// rather than lazy regexes: those were quadratic, and one was cubic, in text a
// model writes (a background agent's report is copied into its parent's
// transcript word for word). This file holds the scans to two promises:
//
//   * THE SAME ANSWERS. Each old pattern is kept here as the reference and
//     compared on real record shapes and on seeded random mixtures of the tags.
//   * TIME LINEAR IN THE TEXT. Inputs that held the event loop for seconds on
//     the old patterns finish in milliseconds.

const { test } = require('node:test');
const assert = require('node:assert');
const t = require('../lib/transcript');

// ---- the old patterns, verbatim, as the reference ---------------------------

const clip = (s, n) => { s = String(s); return s.length > n ? s.slice(0, n) + '…' : s; };
const stripAnsiText = (s) => String(s).replace(/\u001B\[[0-9;?]*[a-zA-Z]/g, '');

function oldDescribe(s) {
  if (/^\s*<local-command-caveat/.test(s)) return null;
  if (/^\s*<system-reminder/.test(s)) return null;
  const cmd = /<command-name>\s*([^<]+?)\s*<\/command-name>/.exec(s);
  if (cmd) {
    const args = /<command-args>\s*([^<]*?)\s*<\/command-args>/.exec(s);
    const text = args && args[1] ? `${cmd[1]} ${args[1]}` : cmd[1];
    return { kind: 'command', text: text.trim() };
  }
  const out = /<local-command-stdout>([\s\S]*?)<\/local-command-stdout>/.exec(s);
  if (out) {
    const body = stripAnsiText(out[1]).trim();
    return body ? { kind: 'command_result', text: clip(body, 300) } : null;
  }
  if (/^\s*\[Image: original \d+x\d+/.test(s)) return null;
  if (/^\s*\[Your previous response/.test(s)) return null;
  if (/<task-notification/.test(s) || /^\s*\[SYSTEM NOTIFICATION/.test(s)) {
    const sum = /<summary>\s*([\s\S]*?)\s*<\/summary>/.exec(s);
    return { kind: 'system', text: sum ? clip(sum[1].replace(/\s+/g, ' '), 160) : 'background task reported back' };
  }
  return { kind: 'system', text: 'injected input' };
}

function oldHuman(s) {
  const stripped = String(s)
    .replace(/<local-command-caveat>[\s\S]*?<\/local-command-caveat>/g, '')
    .replace(/<local-command-stdout>[\s\S]*?<\/local-command-stdout>/g, '')
    .replace(/<command-(name|message|args)>[\s\S]*?<\/command-\1>/g, '')
    .replace(/\[SYSTEM NOTIFICATION - NOT USER INPUT\][\s\S]*?(?=<task-notification|$)/g, '')
    .replace(/<task-notification>[\s\S]*?<\/task-notification>/g, '')
    .replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '')
    .replace(/<\/?(task-notification|system-reminder)[^>]*>/g, '')
    .trim();
  return stripped.length >= 12 ? stripped : '';
}

const OLD_CROSS = /<cross-session-message\b[\s\S]*?<\/cross-session-message>/;
const OLD_AGENT = /<agent-message\b[\s\S]*?<\/agent-message>/;
function oldFirst(s, re) {
  const m = re.exec(s);
  return m ? { text: m[0], index: m.index } : null;
}

