// A seeded mixture of the tags, the pieces around them, and stray brackets.
const PIECES = ['<command-name>', '</command-name>', '<command-args>', '</command-args>', '<command-message>',
  '</command-message>', '<local-command-stdout>', '</local-command-stdout>', '<local-command-caveat>',
  '</local-command-caveat>', '<task-notification>', '</task-notification>', '<system-reminder>', '</system-reminder>',
  '<summary>', '</summary>', '[SYSTEM NOTIFICATION - NOT USER INPUT]', '<cross-session-message from-name="w">',
  '<cross-session-messages>', '</cross-session-message>', '<agent-message from="x">', '<agent-message_x>',
  '</agent-message>', ' ', '   ', '\n', '\t', 'hello world', '/model', 'x', '<', '>', '<b>', 'a<b', 'ok?'];
function mulberry32(a) {
  return () => {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let r = Math.imul(a ^ (a >>> 15), 1 | a);
    r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r;
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}
function mixtures(n, seed) {
  const rnd = mulberry32(seed);
  const out = [];
  for (let i = 0; i < n; i++) {
    const len = Math.floor(rnd() * 24);
    let s = '';
    for (let k = 0; k < len; k++) s += PIECES[Math.floor(rnd() * PIECES.length)];
    out.push(s);
  }
  return out;
}
const ALL = [...REAL, ...mixtures(4000, 20261023)];

// ---- same answers ------------------------------------------------------------

test('describeMachineText answers as the old patterns did', () => {
  for (const s of ALL) assert.deepEqual(t.describeMachineText(s), oldDescribe(s), JSON.stringify(s));
});

test('humanRemainder leaves what the old patterns left', () => {
  for (const s of ALL) assert.equal(t.humanRemainder(s), oldHuman(s), JSON.stringify(s));
});

test('the peer and agent elements are the ones the old patterns found', () => {
  for (const s of ALL) {
    assert.deepEqual(t.firstElement(s, t.CROSS_TAG), oldFirst(s, OLD_CROSS), JSON.stringify(s));
    assert.deepEqual(t.firstElement(s, t.AGENT_TAG), oldFirst(s, OLD_AGENT), JSON.stringify(s));
  }
});

// ---- linear time -------------------------------------------------------------

const timed = (fn) => { const t0 = process.hrtime.bigint(); fn(); return Number(process.hrtime.bigint() - t0) / 1e6; };

test('a run of spaces after an unclosed command tag costs milliseconds, not minutes', () => {
  // 2,000 spaces held the old pattern for ~3 s on this host; it grows with the
  // cube of the run, so a report ending in ten thousand stalled every read.
  for (const w of [2_000, 50_000]) {
    const s = `<task-notification><summary>done</summary><result><command-name>${' '.repeat(w)}x</result></task-notification>`;
    const ms = timed(() => t.describeMachineText(s));
    assert.ok(ms < 200, `${w} spaces took ${ms.toFixed(0)} ms`);
  }
  const args = `<command-name>/x</command-name><command-args>${' '.repeat(50_000)}`;
  assert.ok(timed(() => t.describeMachineText(args)) < 200);
  const sum = `<task-notification><summary>${' '.repeat(50_000)}`;
  assert.ok(timed(() => t.describeMachineText(sum)) < 200);
});

test('thousands of unclosed openings cost milliseconds', () => {
  // 20,000 unclosed `<system-reminder>` held the old replaces ~2.4 s.
  const many = (tag, k) => `a real message first ${tag.repeat(k)}`;
  for (const tag of ['<system-reminder>', '<task-notification>', '<command-name>', '<local-command-stdout>',
    '<task-notification', '<cross-session-message ', '<agent-message ']) {
    const s = many(tag, 20_000);
    const ms = timed(() => {
      t.humanRemainder(s);
      t.describeMachineText(s);
      t.firstElement(s, t.CROSS_TAG);
      t.firstElement(s, t.AGENT_TAG);
    });
    assert.ok(ms < 300, `${tag} x20000 took ${ms.toFixed(0)} ms`);
  }
});
