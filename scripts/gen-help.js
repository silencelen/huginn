#!/usr/bin/env node
'use strict';
// Writes the help body of BOTH clients from client/help-table.txt.
//
// WHY. client/huginn.sh and client/huginn.ps1 each printed a hand-kept copy of
// the same screen, and the copies drifted: one had `devices watch` and the other
// did not, the device rows said "systemd" in one and "a service" in the other,
// and one printed a blank line after the banner where the other ran straight on.
// Each client is ONE shipped file read on machines with no repo, so neither can
// read the table at runtime; the body is spliced into each between markers, and
// --check (scripts/test-client.sh) fails the moment either has been edited away
// from the table. The gen-device-policy.js precedent.
//
//   node scripts/gen-help.js           # write
//   node scripts/gen-help.js --check   # fail if anything would change

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = 'client/help-table.txt';
const CHECK = process.argv.includes('--check');
const MAX = 79;
const DESC_COL = 30;

const raw = fs.readFileSync(path.join(ROOT, SRC), 'utf8').replace(/\r\n/g, '\n');
if (/[^\x00-\x7f]/.test(raw)) fail(`${SRC} is not 7-bit`);
const all = raw.split('\n');
let i = 0;
while (i < all.length && all[i].startsWith('#')) i += 1;
const body = all.slice(i);
while (body.length && body[body.length - 1] === '') body.pop();
if (body[0] !== '') fail(`${SRC}: the body starts with one blank line (after the banner)`);

function fail(msg) { console.error(msg); process.exit(1); }

// ---------------------------------------------------------------- the forms
// `code` is what goes in the file; `shown` is what a person sees, for the
// width check. HOST_HERE is checked in its worst ordinary case (set, to the
// default alias); a longer custom host name may run past the edge, which is
// its own choice.
const LANGS = {
  sh: {
    esc: (s) => s.replace(/\\/g, '\\\\').replace(/\$/g, '\\$').replace(/`/g, '\\`'),
    ph: {
      REPO: ['$HUGINN_REPO', 'silencelen/huginn'],
      HOST_VAR: ['\\$HUGINN_HOST', '$HUGINN_HOST'],
      HOST_HERE: ['${HUGINN_HOST:+, which is $HUGINN_HOST here}', ', which is huginn here'],
    },
    set: (n, v) => [`${n}=${v}`, `${n}=${v}`],
  },
  ps1: {
    esc: (s) => s.replace(/`/g, '``').replace(/\$/g, '`$'),
    ph: {
      REPO: ['$script:HUGINN_REPO', 'silencelen/huginn'],
      HOST_VAR: ['`$env:HUGINN_HOST', '$env:HUGINN_HOST'],
      HOST_HERE: ['$(if ($env:HUGINN_HOST) { ", which is $env:HUGINN_HOST here" })', ', which is huginn here'],
    },
    set: (n, v) => [`\`$env:${n}='${v}'`, `$env:${n}='${v}'`],
  },
};

function render(lang) {
  const L = LANGS[lang];
  return body.map((line, n) => {
    let code = '';
    let shown = '';
    let last = 0;
    const re = /\{([A-Z_]+)(?::([A-Z_]+)=([^}]*))?\}/g;
    let m;
    while ((m = re.exec(line))) {
      const lit = line.slice(last, m.index);
      code += L.esc(lit); shown += lit;
      let pair;
      if (m[1] === 'SET' && m[2]) pair = L.set(m[2], m[3]);
      else if (L.ph[m[1]]) pair = L.ph[m[1]];
      else fail(`${SRC}:${i + n + 1}: unknown placeholder ${m[0]}`);
      code += pair[0]; shown += pair[1];
      last = re.lastIndex;
    }
    const tail = line.slice(last);
    code += L.esc(tail); shown += tail;
    if (shown.length > MAX) fail(`${SRC}:${i + n + 1}: ${shown.length} columns in the ${lang} client (max ${MAX}): ${shown}`);
    // The grammar: a row's description starts at DESC_COL, or the row is a
    // command alone and the description is on the next line.
    if (/^  huginn( |$)/.test(line) && line.length > DESC_COL && line[DESC_COL - 1] !== ' ' && /\S {2,}\S/.test(line.slice(2))) {
      fail(`${SRC}:${i + n + 1}: description not at column ${DESC_COL}: ${line}`);
    }
    return code;
  });
}

const BEGIN = '---8<--- BEGIN GENERATED by scripts/gen-help.js from client/help-table.txt - DO NOT EDIT';
const END = '---8<--- END GENERATED help body';

// ⚠ THE LINE ENDING IS READ FROM THE FILE, NEVER ASSUMED. .gitattributes asks for
// CRLF in a *.ps1 checkout, but the blob is LF and a file restored with
// `git show` (or rewritten by any LF tool) is LF. Splitting an LF file on "\r\n"
// made the whole file ONE line, both markers were found on it, and the splice
// replaced the entire client with the help block (2026-10-13). So: split on
// either ending, write back with the one the file already uses, and refuse to
// write anything that does not keep every line around the block.
const TARGETS = {
  'client/huginn.sh': { open: '  cat <<EOF', close: 'EOF', lang: 'sh' },
  'client/huginn.ps1': { open: '  return @"', close: '"@', lang: 'ps1' },
};

let stale = 0;
for (const [rel, t] of Object.entries(TARGETS)) {
  const abs = path.join(ROOT, rel);
  const cur = fs.readFileSync(abs, 'utf8');
  const eol = /\r\n/.test(cur) ? '\r\n' : '\n';
  const lines = cur.split(/\r?\n/);
  const bs = lines.reduce((a, l, n) => (l.includes(BEGIN) ? [...a, n] : a), []);
  const es = lines.reduce((a, l, n) => (l.includes(END) ? [...a, n] : a), []);
  // Missing or doubled markers: never write, whatever mode was asked for.
  if (bs.length !== 1 || es.length !== 1 || es[0] <= bs[0]) {
    fail(`${rel}: expected exactly one BEGIN and one END help marker, in order ` +
         `(found ${bs.length} and ${es.length}) - not writing anything`);
  }
  const b = bs[0];
  const e = es[0];
  const block = [`  # ${BEGIN}`, t.open, ...render(t.lang), t.close, `  # ${END}`];
  const out = [...lines.slice(0, b), ...block, ...lines.slice(e + 1)];
  // THE TRUNCATION GUARD. Everything before BEGIN and after END survives
  // verbatim, and the file shrinks by no more than the old block's length.
  const keptBefore = lines.slice(0, b).every((l, n) => out[n] === l);
  const tail = lines.slice(e + 1);
  const keptAfter = tail.every((l, n) => out[out.length - tail.length + n] === l);
  const oldBlock = e - b + 1;
  if (!keptBefore || !keptAfter || out.length < lines.length - oldBlock) {
    fail(`${rel}: the splice would not keep the file around the help block ` +
         `(${lines.length} lines -> ${out.length}) - refusing to write`);
  }
  const next = out.join(eol);
  if (next === cur) continue;
  if (CHECK) { console.error(`STALE: ${rel}'s help body differs from ${SRC}`); stale += 1; continue; }
  fs.writeFileSync(abs, next);
  console.log(`wrote ${rel} (${lines.length} -> ${out.length} lines)`);
}
if (stale) fail('Run: node scripts/gen-help.js   - and READ the diff.');
if (CHECK) console.log(`help: both clients match ${SRC}`);
