#!/usr/bin/env node
'use strict';
// Expands shared/device-policy.json into the things that cannot read JSON at the
// moment they need it.
//
// WHY THIS EXISTS. Two runners build the argv for a remote request — one in
// Kotlin inside the desktop app, one in Node for headless machines — and the
// daemon holds a copy of the scope lattice for its pre-check. Three programs,
// three languages, one rule. Left to hand-editing they drift, and the drift is
// invisible: a runner that grants Bash where the policy says `look` behaves
// perfectly right up until it doesn't, and nothing in the UI would look wrong.
//
// The Node runner reads the JSON directly at runtime, so it needs nothing from
// here. Kotlin cannot (no filesystem in commonMain, and a resource loader would
// mean the policy could be swapped underneath a signed binary), so its table is
// generated and checked in.
//
// The case matrix is the actual contract: every (scope, locked, mode) with the
// argv it must produce, asserted from BOTH runners. Comparing the two runners to
// each other would let them be wrong in the same way; comparing both to a matrix
// a person can read makes the rule reviewable.
//
//   node scripts/gen-device-policy.js           # write
//   node scripts/gen-device-policy.js --check   # fail if anything would change

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const P = JSON.parse(fs.readFileSync(path.join(ROOT, 'shared/device-policy.json'), 'utf8'));
const CHECK = process.argv.includes('--check');

const BANNER = (from) => `// GENERATED by scripts/gen-device-policy.js from ${from} — DO NOT EDIT.
// Change the policy there and re-run the generator;
// server/appd/test/device-policy-cases.test.js fails if they have drifted apart.`;

// ---------------------------------------------------------------- the rules
// The reference implementation, and the only place they are written as code
// rather than as data. Everything else is asserted against what this produces.

const at = (s) => P.scopes.indexOf(s);
const effective = (scope, locked) => (locked ? P.lockDropsTo : scope);
const allows = (scope, mode) => at(scope) >= at(P.modeNeeds[mode] ?? 'work');

function refusal(scope, locked, mode) {
  if (allows(effective(scope, locked), mode)) return null;
  return locked
    ? P.refusals.locked
    : P.refusals.scope.replace('{scope}', scope).replace('{mode}', mode);
}

function argvFor(scope, locked, mode) {
  const act = mode === 'act' && allows(effective(scope, locked), 'act');
  const argv = P.streamFlags.slice();
  argv.push('--allowedTools', P.tools[act ? 'act' : 'look'].allowed.join(' '));
  const denied = P.tools[act ? 'act' : 'look'].denied;
  if (denied.length) argv.push('--disallowedTools', denied.join(' '));
  return argv;
}

// `work` is the only scope that starts anywhere but home — and only when it is
// in force, which a locked machine's is not.
const cwdKind = (scope, locked) => (effective(scope, locked) === 'work' ? 'root' : 'home');

// ------------------------------------------------------------- the matrix

const cases = [];
for (const scope of P.scopes) {
  for (const locked of [false, true]) {
    for (const mode of Object.keys(P.modeNeeds)) {
      cases.push({
        scope,
        locked,
        mode,
        effectiveScope: effective(scope, locked),
        actGranted: mode === 'act' && allows(effective(scope, locked), 'act'),
        refusal: refusal(scope, locked, mode),
        cwd: cwdKind(scope, locked),
        argv: argvFor(scope, locked, mode),
      });
    }
  }
}

const casesJson = JSON.stringify({
  _comment: [
    'GENERATED by scripts/gen-device-policy.js — DO NOT EDIT.',
    'Every combination of (scope, locked, mode) and the exact argv a remote',
    'request must turn into. Both runners are tested against this file, so a',
    'change here is a change to what a request may do to somebody\'s computer;',
    'read the diff, do not just regenerate it.',
    'argv omits --model/--effort/--resume/--append-system-prompt: those ride along',
    'unchanged whatever the scope, and are covered by DevicePolicyTest.',
    'A refused case still carries an argv on purpose. The refusal is the first',
    'fence and the runner never spawns — but if it ever did, the argv it would',
    'have used must still be the read-only one. Two fences, both asserted.',
  ],
  cases,
}, null, 2) + '\n';

// -------------------------------------------------------------- kotlin table

const kList = (xs) => xs.map((x) => JSON.stringify(x)).join(', ');
const kt = `${BANNER('shared/device-policy.json')}

package com.silencelen.huginn.device

/**
 * The policy as data. [DevicePolicy] is the reasoning; this is the table it reads.
 *
 * Generated so that this file and the headless runner cannot disagree — they are
 * the same rule expressed for two runtimes, and the one thing that must never
 * happen is for one of them to quietly grant more than the other.
 */
internal object DevicePolicyTable {
    val SCOPES: List<String> = listOf(${kList(P.scopes)})
    val MODE_NEEDS: Map<String, String> = mapOf(${Object.entries(P.modeNeeds).map(([k, v]) => `${JSON.stringify(k)} to ${JSON.stringify(v)}`).join(', ')})
    const val LOCK_DROPS_TO: String = ${JSON.stringify(P.lockDropsTo)}

    val STREAM_FLAGS: List<String> = listOf(${kList(P.streamFlags)})

    const val LOOK_ALLOWED: String = ${JSON.stringify(P.tools.look.allowed.join(' '))}
    const val LOOK_DENIED: String = ${JSON.stringify(P.tools.look.denied.join(' '))}
    const val ACT_ALLOWED: String = ${JSON.stringify(P.tools.act.allowed.join(' '))}
    const val ACT_DENIED: String = ${JSON.stringify(P.tools.act.denied.join(' '))}

    const val REFUSAL_LOCKED: String = ${JSON.stringify(P.refusals.locked)}
    const val REFUSAL_SCOPE: String = ${JSON.stringify(P.refusals.scope)}
}
`;

// --------------------------------------------------------- kotlin case test

const ktCase = (c) => `        Case(
            scope = ${JSON.stringify(c.scope)}, locked = ${c.locked}, mode = ${JSON.stringify(c.mode)},
            effective = ${JSON.stringify(c.effectiveScope)}, refusal = ${c.refusal === null ? 'null' : JSON.stringify(c.refusal)},
            cwd = ${JSON.stringify(c.cwd)}, argv = listOf(${kList(c.argv)}),
        ),`;

const ktTest = `${BANNER('shared/device-policy-cases.json')}

package com.silencelen.huginn

import com.silencelen.huginn.data.DeviceWork
import com.silencelen.huginn.device.DevicePolicy
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * The desktop runner against the shared case matrix.
 *
 * The headless Node runner is driven over the same matrix by
 * server/appd/test/device-policy-cases.test.js. Two runtimes, one table, and a
 * failure here means a remote request would do something different depending on
 * which kind of machine it landed on.
 */
class DevicePolicyCasesTest {

    private data class Case(
        val scope: String, val locked: Boolean, val mode: String,
        val effective: String, val refusal: String?,
        val cwd: String, val argv: List<String>,
    )

    private val cases = listOf(
${cases.map(ktCase).join('\n')}
    )

    @Test
    fun everyCaseProducesTheArgvTheMatrixSays() {
        for (c in cases) {
            val scope = DevicePolicy.parse(c.scope)
            val where = "\${c.scope}/locked=\${c.locked}/\${c.mode}"
            assertEquals(c.effective, DevicePolicy.wire(DevicePolicy.effective(scope, c.locked)), where)
            assertEquals(c.refusal, DevicePolicy.refusal(scope, c.locked, c.mode), where)
            val work = DeviceWork(id = "w", chatId = "c", prompt = "p", mode = c.mode)
            assertEquals(c.argv, DevicePolicy.argvFor(work, scope, c.locked, root = "/root-dir"), where)
            val expected = if (c.cwd == "root") "/root-dir" else "/home-dir"
            assertEquals(expected, DevicePolicy.cwdFor(scope, c.locked, "/root-dir", "/home-dir"), where)
        }
    }
}
`;

// ------------------------------------------------------------- appd table

const js = `'use strict';
${BANNER('shared/device-policy.json')}
//
// The daemon needs only the lattice: it never sends tool grants, so the tool
// lists below its horizon are deliberately absent here. What it does with this is
// decide whether to offer work at all, so that "that machine is locked" is said
// at the moment somebody asks instead of a minute later in a transcript.

module.exports = {
  SCOPES: ${JSON.stringify(P.scopes)},
  MODE_NEEDS: ${JSON.stringify(P.modeNeeds)},
  LOCK_DROPS_TO: ${JSON.stringify(P.lockDropsTo)},
};
`;

// ------------------------------------------------------------------ write

// --------------------------------------------------------- the node runner
//
// The headless runner ships as ONE file to machines that have no clone of this
// repo, so its copy of the policy is injected rather than read from disk beside
// it. A second file to install is a second file to forget, and a runner that
// found no policy next to it would have to either refuse to start or invent one —
// and inventing one is exactly the failure this whole arrangement exists to make
// impossible.

const RUNNER_REL = 'client/huginn-device';
const BEGIN = '// ---8<--- GENERATED POLICY';
const END = '// ---8<--- END GENERATED POLICY';

function injectRunner() {
  const file = path.join(ROOT, RUNNER_REL);
  const text = fs.readFileSync(file, 'utf8');
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < 0) throw new Error(`${RUNNER_REL} has lost its GENERATED POLICY markers`);
  const head = text.slice(0, a);
  const tail = text.slice(text.indexOf('\n', b) + 1);
  // Comments stripped: the runner is read on machines that will never see the
  // policy file, and a hundred lines of rationale pasted mid-program helps nobody.
  const bare = JSON.parse(JSON.stringify(P, (k, v) => (k === '_comment' ? undefined : v)));
  const block = `${BEGIN} — scripts/gen-device-policy.js — DO NOT EDIT ---8<---
const POLICY = ${JSON.stringify(bare, null, 2)};
${END} ---8<---
`;
  return head + block + tail;
}

const outputs = [
  ['shared/device-policy-cases.json', casesJson],
  [RUNNER_REL, injectRunner()],
  ['mobile/core/src/commonMain/kotlin/com/silencelen/huginn/device/DevicePolicyTable.kt', kt],
  ['mobile/core/src/commonTest/kotlin/com/silencelen/huginn/DevicePolicyCasesTest.kt', ktTest],
  ['server/appd/lib/device-policy-table.js', js],
];

let stale = 0;
for (const [rel, text] of outputs) {
  const file = path.join(ROOT, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === text) { if (!CHECK) console.log(`  ok    ${rel}`); continue; }
  if (CHECK) { console.error(`  STALE ${rel}`); stale += 1; continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`  wrote ${rel}`);
}

if (CHECK && stale) {
  console.error(`\n${stale} generated file(s) do not match shared/device-policy.json.`);
  console.error('Run: node scripts/gen-device-policy.js   — and READ the diff.');
  process.exit(1);
}
if (CHECK) console.log(`device policy: ${outputs.length} generated file(s) in sync`);
