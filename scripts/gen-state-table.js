#!/usr/bin/env node
'use strict';
// Expands server/lib/state-table.json into one reader per language that prints a
// state: bash (the server/bin renderers source it), python (huginn-headroom
// imports it) and node (huginn-projects requires it; the daemon requires the copy
// that deploy.sh ships beside its other lib/*.js).
//
// WHY GENERATED, not each reader parsing the JSON at runtime: bash cannot parse
// JSON without jq, and a renderer that dies because jq is missing is worse than
// one that prints the wrong mark. So the data is written out once per language,
// from one file, and this script's --check (run by scripts/test-client.sh and by
// server/appd/test/state-table.test.js) fails the moment one of them has been
// hand-edited away from the source. The gen-device-policy.js precedent.
//
// Every output is PURE 7-BIT: the glyphs are written as escapes, so a reader can
// travel over scp to a Windows box or be grepped with LC_ALL=C like the clients.
//
//   node scripts/gen-state-table.js           # write
//   node scripts/gen-state-table.js --check   # fail if anything would change

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = 'server/lib/state-table.json';
const T = JSON.parse(fs.readFileSync(path.join(ROOT, SRC), 'utf8'));
const CHECK = process.argv.includes('--check');

const states = T.states;
const KEYS = ['running', 'needsYou', 'waiting', 'ok', 'error', 'info', 'shell'];
if (states.map((s) => s.key).join() !== KEYS.join()) {
  console.error(`${SRC}: the seven states, in order, are ${KEYS.join(', ')}`);
  process.exit(1);
}
const marks = states.map((s) => s.mark);
if (new Set(marks).size !== marks.length || marks.some((m) => !/^[\x21-\x7e]$/.test(m))) {
  console.error(`${SRC}: every mark is one distinct printable 7-bit character`);
  process.exit(1);
}

// running -> RUNNING, needsYou -> NEEDS_YOU
const shKey = (k) => k.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase();
const utf8Esc = (s) => [...Buffer.from(s, 'utf8')].map((b) => `\\x${b.toString(16).padStart(2, '0')}`).join('');
const uEsc = (s) => [...s].map((c) => {
  const n = c.codePointAt(0);
  return n < 0x80 ? c : `\\u${n.toString(16).padStart(4, '0')}`;
}).join('');
const shq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

const banner = (c) => [
  `${c} GENERATED by scripts/gen-state-table.js from ${SRC} - DO NOT EDIT.`,
  `${c} Change the table there and re-run the generator; scripts/test-client.sh and`,
  `${c} server/appd/test/state-table.test.js fail if this has drifted from it.`,
].join('\n');

// ------------------------------------------------------------------ bash
function genSh() {
  const L = [];
  L.push('# shellcheck shell=bash disable=SC2034');
  L.push(banner('#'));
  L.push('#');
  L.push('# The brand state table (assets/brand/BRAND.md section 4). For each KEY in');
  L.push(`# HUGINN_STATE_KEYS this defines, and exports so a \`python3 -c\` inside a renderer`);
  L.push('# can read them from os.environ:');
  L.push('#   HUGINN_WORD_<KEY>   the word            (working, needs you, waiting, ...)');
  L.push('#   HUGINN_MARK_<KEY>   the 7-bit mark      (anything that may reach PowerShell 5.1)');
  L.push('#   HUGINN_GLYPH_<KEY>  the glyph, as UTF-8 (titles, tmux; huginn_state_glyph picks)');
  L.push('#   HUGINN_SGR_<KEY>    the 16-colour slot  (a number; the terminal owns the hue)');
  L.push(`HUGINN_STATE_KEYS=${shq(states.map((s) => shKey(s.key)).join(' '))}`);
  for (const s of states) {
    const K = shKey(s.key);
    L.push(`HUGINN_WORD_${K}=${shq(s.word)}; HUGINN_MARK_${K}=${shq(s.mark)}; ` +
      `HUGINN_GLYPH_${K}=$'${utf8Esc(s.glyph)}'; HUGINN_SGR_${K}=${s.sgr}`);
    L.push(`export HUGINN_WORD_${K} HUGINN_MARK_${K} HUGINN_GLYPH_${K} HUGINN_SGR_${K}`);
  }
  L.push('export HUGINN_STATE_KEYS');
  L.push('');
  L.push('# huginn_state_glyph KEY - the glyph on a UTF-8 locale, the 7-bit mark otherwise.');
  L.push('huginn_state_glyph() {');
  L.push('  local g="HUGINN_GLYPH_$1" m="HUGINN_MARK_$1"');
  L.push('  case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in');
  L.push('    *[Uu][Tt][Ff]-8*|*[Uu][Tt][Ff]8*) printf \'%s\' "${!g:-}" ;;');
  L.push('    *) printf \'%s\' "${!m:-}" ;;');
  L.push('  esac');
  L.push('}');
  return L.join('\n') + '\n';
}

// ---------------------------------------------------------------- python
function genPy() {
  const L = [];
  L.push(banner('#'));
  L.push('#');
  L.push('# The brand state table (assets/brand/BRAND.md section 4). Loaded with');
  L.push('# runpy.run_path (the hyphen keeps it from being an importable name):');
  L.push('#   WORD["needsYou"] == "needs you", MARK["needsYou"] == "!", GLYPH, SGR alike.');
  L.push('STATES = [');
  for (const s of states) {
    L.push(`    {"key": "${s.key}", "word": "${s.word}", "glyph": "${uEsc(s.glyph)}", "mark": "${s.mark}", ` +
      `"oneRow": ${s.oneRow ? `"${s.oneRow}"` : 'None'}, "sgr": ${s.sgr}},`);
  }
  L.push(']');
  L.push('WORD = dict((s["key"], s["word"]) for s in STATES)');
  L.push('MARK = dict((s["key"], s["mark"]) for s in STATES)');
  L.push('GLYPH = dict((s["key"], s["glyph"]) for s in STATES)');
  L.push('SGR = dict((s["key"], s["sgr"]) for s in STATES)');
  return L.join('\n') + '\n';
}

// ------------------------------------------------------------------ node
function genJs() {
  const L = [];
  L.push("'use strict';");
  L.push(banner('//'));
  L.push('//');
  L.push('// The brand state table (assets/brand/BRAND.md section 4): WORD.needsYou is');
  L.push("// 'needs you', MARK.needsYou '!', GLYPH.needsYou the triangle. MARK is what");
  L.push('// a terminal renderer prints; GLYPH is what Telegram and titles lead with.');
  L.push('const STATES = Object.freeze([');
  for (const s of states) {
    L.push(`  Object.freeze({ key: '${s.key}', word: '${s.word}', glyph: '${uEsc(s.glyph)}', mark: '${s.mark}', ` +
      `oneRow: ${s.oneRow ? `'${s.oneRow}'` : 'null'}, sgr: ${s.sgr} }),`);
  }
  L.push(']);');
  L.push('const pick = (f) => Object.freeze(Object.fromEntries(STATES.map((s) => [s.key, s[f]])));');
  L.push('module.exports = { STATES, WORD: pick(\'word\'), MARK: pick(\'mark\'), GLYPH: pick(\'glyph\'), SGR: pick(\'sgr\') };');
  return L.join('\n') + '\n';
}

const OUT = {
  'server/lib/state-table.sh': genSh(),
  'server/lib/state-table.py': genPy(),
  'server/lib/state-table.js': genJs(),
  'server/appd/lib/state-table.js': genJs(),
};

let stale = 0;
for (const [rel, body] of Object.entries(OUT)) {
  if (/[^\x00-\x7f]/.test(body)) { console.error(`${rel}: generated text is not 7-bit`); process.exit(1); }
  const abs = path.join(ROOT, rel);
  let cur = null;
  try { cur = fs.readFileSync(abs, 'utf8'); } catch { cur = null; }
  if (cur === body) continue;
  if (CHECK) { console.error(`STALE: ${rel} differs from what ${SRC} generates`); stale += 1; continue; }
  fs.writeFileSync(abs, body);
  console.log(`wrote ${rel}`);
}
if (stale) {
  console.error('Run: node scripts/gen-state-table.js   - and READ the diff.');
  process.exit(1);
}
if (CHECK) console.log('state table: every reader matches ' + SRC);
