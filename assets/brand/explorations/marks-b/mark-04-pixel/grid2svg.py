#!/usr/bin/env python3
"""grid2svg.py — turn a pixel grid into a crisp-edged SVG of unit squares.

    python3 grid2svg.py grid.txt name out.svg [--ink #161310] [--inverse] [--tile] [--pad N]

The output is ONE merged path (each run of ink cells is a rectangle subpath; fill-rule nonzero
means shared edges never show) with shape-rendering="crispEdges", so a 16x16 grid at 16px is
pixel-exact in every renderer. --inverse swaps ink/bone and fills the ground; --tile puts the
grid on a rounded square bone tile (pad is in cells; the set's tile radius rule is 22.5% of the
side, the same as mark-05 and mark-06). Default pad is 0: the grid IS the viewBox, so a 16-grid
at 16 px and a 32-grid at 32 px stay on whole pixels. Put any margin in the container.

Pixel-exactness holds at INTEGER scales only (16 at 16/32/48/..., 32 at 32/64/96/...). At a
non-integer scale (a 125% or 150% desktop tray, Android hdpi) rows come out 1 px and 2 px
wide; use grid2png.py there, which pads instead of scaling.
"""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0] if '/' in __file__ else '.')
from grid2text import load

INK, BONE = '#161310', '#E8E2DA'

def path_for(rows, ox=0, oy=0):
    d = []
    for y, r in enumerate(rows):
        x = 0
        while x < len(r):
            if r[x] == '#':
                x0 = x
                while x < len(r) and r[x] == '#': x += 1
                d.append(f'M{x0+ox},{y+oy}h{x-x0}v1h{-(x-x0)}z')
            else:
                x += 1
    return ''.join(d)

def main():
    a = sys.argv[1:]
    path, name, out = a[0], a[1], a[2]
    ink = a[a.index('--ink') + 1] if '--ink' in a else INK
    inverse, tile = '--inverse' in a, '--tile' in a
    pad = int(a[a.index('--pad') + 1]) if '--pad' in a else 0
    rows = load(path)[name]
    w, h = len(rows[0]), len(rows)
    W, H = w + 2 * pad, h + 2 * pad
    body = path_for(rows, pad, pad)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W*16}" height="{H*16}">',
             f'  <!-- Huginn pixel raven ({name}, {w}x{h} grid{", pad " + str(pad) if pad else ""}). Generated by grid2svg.py from grid.txt; edit the grid, not this file. -->']
    if tile:
        r = max(1, round(W * 0.225))
        parts.append(f'  <rect width="{W}" height="{H}" rx="{r}" fill="{BONE}"/>')
        parts.append(f'  <path d="{body}" fill="{INK}" shape-rendering="crispEdges"/>')
    elif inverse:
        parts.append(f'  <rect width="{W}" height="{H}" fill="{INK}"/>')
        parts.append(f'  <path d="{body}" fill="{BONE}" shape-rendering="crispEdges"/>')
    else:
        parts.append(f'  <path d="{body}" fill="{ink}" shape-rendering="crispEdges"/>')
    parts.append('</svg>')
    open(out, 'w').write('\n'.join(parts) + '\n')
    print(out)

if __name__ == '__main__':
    main()
