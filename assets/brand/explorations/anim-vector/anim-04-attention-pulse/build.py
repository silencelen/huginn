#!/usr/bin/env python3
"""build.py — bake anim-04-attention-pulse/anim.svg from the canonical mark, then
anim.html via wrap.mjs. 64-unit canvas = the 64 px tray sprite. The raven and badge sit
exactly where TrayIcons.kt draws them for ATTENTION (raven in a 50x42 box at (0,22),
badge centre (53,11) r 9); the ring is new. See ../tray-sprite-spec.md.

Revision 2 (after review):
- The transition starts from the IDLE/WORKING icon: TrayIcons.kt draws those with the
  raven in a 60x60 box at (2,2), so the first 300 ms slide and shrink the raven from
  that box to the ATTENTION box (cubic-bezier(0.2,0,0,1)); the badge pops and the ring
  starts when the slide ends. Before, the sequence began after that snap.
- The ring animates `r` and `stroke-width` directly (no transform, no
  vector-effect), so the stroke is the spec's 4 -> 1.5 px ON THE 64 px SPRITE and scales
  with the icon like the Java2D version; the old non-scaling-stroke made the ring 4 px
  thick at any size and overstated it 2.7-4x at 16/24 px.
- The badge pop has no overshoot (0 -> 1, 240 ms): an 8 % overshoot at 10 fps was one
  flickering frame.
- Resting values (no animations) are the ATTENTION icon (badge visible), not IDLE.

    python3 build.py            # writes anim.svg, anim.html
    python3 build.py --table    # prints the 10 fps / 24 fps frame tables for the spec
"""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
RAVEN = os.path.abspath(os.path.join(HERE, '..', '..', '..', 'raven.svg'))
src = open(RAVEN, encoding='utf-8').read()
D = ' '.join(re.search(r'<path[^>]*\sd="([^"]+)"', src, re.S).group(1).split())

# mark bbox in path coords: x 10..94.6, y 17..69 (84.6 x 52), as RavenMark.kt scales it.
BW, BH, BX, BY = 84.6, 52.0, 10.0, 17.0
def place(x, y, w, h):
    """RavenMark.draw(g, x, y, w, h): fit the bbox in the box, centred on the free axis -> (tx, ty, scale)"""
    s = min(w / BW, h / BH)
    return x + (w - BW * s) / 2 - BX * s, y + (h - BH * s) / 2 - BY * s, s
IDLE = place(2, 2, 60, 60)          # TrayIcons.kt IDLE / WORKING
ATTN = place(0, 22, 50, 42)         # TrayIcons.kt ATTENTION
SLIDE, POP, RING, CYCLES = 0.30, 0.24, 1.2, 2
E = 'cubic-bezier(0.2, 0, 0, 1)'
R0, R1, W0, W1 = 17.0, 27.2, 4.0, 1.5          # ring radius / stroke on the 64 px sprite

def bez(u, x1=0.2, y1=0.0, x2=0.0, y2=1.0):
    """CSS cubic-bezier(x1,y1,x2,y2) evaluated at progress u (solve x for the parameter, read y)."""
    u = min(max(u, 0.0), 1.0)
    lo, hi = 0.0, 1.0
    for _ in range(40):
        t = (lo + hi) / 2
        x = 3 * (1 - t) ** 2 * t * x1 + 3 * (1 - t) * t ** 2 * x2 + t ** 3
        lo, hi = (t, hi) if x < u else (lo, t)
    t = (lo + hi) / 2
    return 3 * (1 - t) ** 2 * t * y1 + 3 * (1 - t) * t ** 2 * y2 + t ** 3

def ring_at(u):
    """u in [0,1) within a 1.2 s cycle -> (r, stroke, alpha) or None when not drawn"""
    if u >= 0.75: return None
    p = bez(u / 0.75)
    a = 0.85 * bez(u / 0.08) if u < 0.08 else 0.85 * (1 - (u - 0.08) / 0.67)
    return R0 + (R1 - R0) * p, W0 - (W0 - W1) * p, a

def table(fps):
    dt = 1.0 / fps
    rows = []
    n_slide = round(SLIDE * fps); n_cycle = round(RING * fps)
    for i in range(n_slide + CYCLES * n_cycle + 1):
        t = i * dt
        if t < SLIDE - 1e-9:
            p = bez(t / SLIDE)
            box = tuple(a + (b - a) * p for a, b in zip((2, 2, 60, 60), (0, 22, 50, 42)))
            rows.append((i, t, 'slide', box, None, None))
        else:
            tt = t - SLIDE
            badge = min(bez(tt / POP), 1.0) if tt < POP else 1.0
            cyc = int(tt // RING); u = (tt - cyc * RING) / RING
            ring = ring_at(u) if cyc < CYCLES else None
            rows.append((i, t, f'cycle {cyc + 1}' if cyc < CYCLES else 'rest', (0, 22, 50, 42), badge, ring))
    return rows

if '--table' in sys.argv:
    for fps in (10, 24):
        print(f'\n### {fps} fps  (tick = {1000 / fps:.1f} ms)\n')
        print('| tick | t (s) | phase | raven box (x, y, w, h) | badge scale | ring r | stroke | ring alpha |')
        print('|---|---|---|---|---|---|---|---|')
        for i, t, ph, box, badge, ring in table(fps):
            b = '(%.1f, %.1f, %.1f, %.1f)' % box
            bs = '-' if badge is None else f'{badge:.2f}'
            rr = ('%.1f | %.2f | %.2f' % ring) if ring else '- | - | 0'
            print(f'| {i} | {t:.2f} | {ph} | {b} | {bs} | {rr} |')
    sys.exit(0)

(ix, iy, is_), (ax, ay, as_) = IDLE, ATTN
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 64 64" width="256" height="256">
  <title>Huginn tray, attention</title>
  <!-- anim-04-attention-pulse. GENERATED by build.py; do not hand-edit. 64-unit canvas =
       the 64 px tray sprite, so every number here is a sprite pixel. Starts as the IDLE
       icon (raven in a 60x60 box at (2,2)), slides to the ATTENTION layout (50x42 box at
       (0,22), badge at (53,11) r 9) in {SLIDE*1000:.0f} ms: EXACTLY the geometry TrayIcons.kt draws
       for both states, so the first and last frames are today's icons. Then the badge
       pops ({POP*1000:.0f} ms) and a ring emerges from behind the raven, expands and fades:
       {RING:g} s per cycle, {CYCLES} cycles, then rest. Ring r {R0:g} -> {R1:g}, stroke {W0:g} -> {W1:g} sprite px.
       The mark is <path id="raven"> (canonical path, one swap). Resting state (no
       animations) = the ATTENTION icon. -->
  <style>
    svg {{ --ink: #161310; }}
    .ink {{ fill: var(--ink); }}
    .mark {{
      transform: translate({ax:.3f}px, {ay:.3f}px) scale({as_:.4f});
      animation: huginn-slide {SLIDE:g}s {E} both;
    }}
    .ring {{
      fill: none; stroke: var(--ink);
      r: {R0:g}px; stroke-width: {W0:g}; opacity: 0;
      animation: huginn-ring {RING:g}s linear {SLIDE:g}s {CYCLES} both;
    }}
    .badge {{
      transform-box: fill-box; transform-origin: center;
      transform: scale(1); opacity: 1;
      animation: huginn-badge {POP:g}s {E} {SLIDE:g}s both;
    }}
    @keyframes huginn-slide {{
      from {{ transform: translate({ix:.3f}px, {iy:.3f}px) scale({is_:.4f}); }}
      to   {{ transform: translate({ax:.3f}px, {ay:.3f}px) scale({as_:.4f}); }}
    }}
    @keyframes huginn-ring {{
      0%   {{ r: {R0:g}px; opacity: 0;    stroke-width: {W0:g};   animation-timing-function: {E}; }}
      8%   {{ opacity: 0.85; }}
      75%  {{ r: {R1:g}px; opacity: 0;    stroke-width: {W1:g}; }}
      100% {{ r: {R1:g}px; opacity: 0;    stroke-width: {W1:g}; }}
    }}
    @keyframes huginn-badge {{
      from {{ transform: scale(0); opacity: 0; }}
      15%  {{ opacity: 1; }}
      to   {{ transform: scale(1); opacity: 1; }}
    }}
    @media (prefers-reduced-motion: reduce) {{
      .mark, .ring, .badge {{ animation: none; }}
    }}
  </style>
  <defs>
    <path id="raven" fill-rule="evenodd" d="{D}"/>
  </defs>
  <!-- ring first: it is BEHIND the raven and emerges from under it -->
  <circle class="ring" cx="29" cy="36" r="{R0:g}"/>
  <g class="mark">
    <use href="#raven" class="ink"/>
  </g>
  <circle class="ink badge" cx="53" cy="11" r="9"/>
</svg>
'''
open(os.path.join(HERE, 'anim.svg'), 'w', encoding='utf-8').write(svg)
subprocess.run(['node', os.path.join(HERE, '..', 'wrap.mjs'), os.path.join(HERE, 'anim.svg'),
                os.path.join(HERE, 'anim.html'), 'Huginn — anim-04-attention-pulse'], check=True)
print(f'built: idle translate({ix:.3f},{iy:.3f}) scale {is_:.4f}; attention translate({ax:.3f},{ay:.3f}) scale {as_:.4f}')
